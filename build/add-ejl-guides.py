def main():
    with io.open(DATA, 'r', encoding='utf-8', newline='') as f:
        txt = f.read()
    if MARK in txt:
        print('data.js: 4 篇 ejl 攻略已存在，跳过')
        return
    anchor = ']\n\n/* Node 侧（构建脚本）可直接 require 这份数据 */'
    if txt.count(anchor) != 1:
        raise SystemExit('data.js: 未找到唯一数组结尾锚点')
    head, tail = txt.split(anchor)
    if not head.rstrip().endswith('}'):
        raise SystemExit('data.js: 数组最后一项结构异常')
    # 原最后一项没有逗号；补上后再接 4 个新对象，最后一项同样不带逗号
    new = head.rstrip() + ',\n' + BLOCK.strip() + '\n' + anchor + tail
    with io.open(DATA, 'w', encoding='utf-8', newline='') as f:
        f.write(new)
    print('data.js: 追加 4 篇 ejl 攻略（51 → 55 篇）')


if __name__ == '__main__':
    main()
